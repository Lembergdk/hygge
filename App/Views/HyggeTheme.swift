/// Warm Nordic (locked from the redesign spec): Paper, Ember, Gold, Butter,
/// sage — warm, calm, matte. One saturated element per screen; the rest is
/// paper and white. Every token is appearance-aware: dark mode is a real
/// warm-charcoal mapping, not light colors forced onto a dark screen.
enum HyggeTheme {
    private static func dynamic(light: (CGFloat, CGFloat, CGFloat),
                                dark: (CGFloat, CGFloat, CGFloat)) -> Color {
        Color(UIColor { traits in
            let c = traits.userInterfaceStyle == .dark ? dark : light
            return UIColor(red: c.0, green: c.1, blue: c.2, alpha: 1)
        })
    }

    // Light values are the exact V1 spec hexes (docs/design/atoms/README.md).
    static let paper = dynamic(light: (0.980, 0.965, 0.937), dark: (0.145, 0.110, 0.086))      // #FAF6EF
    static let paperDeep = dynamic(light: (0.945, 0.902, 0.835), dark: (0.196, 0.153, 0.118))
    static let ink = dynamic(light: (0.169, 0.137, 0.125), dark: (0.949, 0.902, 0.827))        // #2B2320
    static let card = dynamic(light: (1.0, 1.0, 1.0), dark: (0.227, 0.180, 0.145))             // #FFFFFF
    static let sage = dynamic(light: (0.440, 0.610, 0.470), dark: (0.561, 0.722, 0.612))
    static let sageDeep = dynamic(light: (0.243, 0.361, 0.220), dark: (0.631, 0.800, 0.690))   // #3E5C38
    /// Coral: flame outer + pinned chip. NEVER carries button text (2.8:1).
    static let ember = dynamic(light: (1.0, 0.420, 0.341), dark: (1.0, 0.500, 0.410))          // #FF6B57
    /// Primary buttons: white text passes at 5.1:1.
    static let emberDeep = dynamic(light: (0.788, 0.227, 0.149), dark: (0.860, 0.340, 0.240))  // #C93A26
    static let butter = dynamic(light: (1.0, 0.773, 0.239), dark: (0.949, 0.820, 0.506))       // gold #FFC53D
    static let butterTint = dynamic(light: (1.0, 0.953, 0.839), dark: (0.330, 0.275, 0.165))   // #FFF3D6
    static let butterText = dynamic(light: (0.541, 0.353, 0.0), dark: (0.950, 0.800, 0.470))   // #8A5A00
    static let hairline = Color(UIColor { traits in
        traits.userInterfaceStyle == .dark
            ? UIColor.white.withAlphaComponent(0.10)
            : UIColor.black.withAlphaComponent(0.07)
    })
    static let secondary = dynamic(light: (0.478, 0.416, 0.380), dark: (0.741, 0.671, 0.588)) // muted #7A6A61
    /// Selected-tile peach from the mocks.
    static let peach = dynamic(light: (0.984, 0.886, 0.820), dark: (0.353, 0.235, 0.180))
    /// Soft sage wash for stat cards.
    static let sageTint = dynamic(light: (0.894, 0.922, 0.867), dark: (0.290, 0.365, 0.310))   // #E4EBDD
    /// The flame's face is ink (#2B2320) in both appearances.
    static let faceBrown = Color(red: 0.169, green: 0.137, blue: 0.125)
    /// Text ON sage-family fills: white on deep sage (light mode), ink on
    /// the pale sage the same token becomes in dark mode. Always ≥4.5:1.
    static let onSage = dynamic(light: (1.0, 1.0, 1.0), dark: (0.169, 0.137, 0.125))
}

extension View {
    func hyggeCard(radius: CGFloat = 22) -> some View {
        background(HyggeTheme.card, in: RoundedRectangle(cornerRadius: radius))
            .overlay(RoundedRectangle(cornerRadius: radius).stroke(HyggeTheme.hairline, lineWidth: 1))
            .shadow(color: Color.black.opacity(0.10), radius: 16, y: 6)
    }
}

/// The approved left-facing flame character artwork (walking flame, soft
/// 3D depth). Generated by scripts/make-flame-assets.py.
struct FlameMark: View {
    var size: CGFloat = 34
    var body: some View {
        Image("FlameCharacter")
            .resizable()
            .scaledToFit()
            .frame(width: size, height: size * 1.25)
            .accessibilityHidden(true)
    }
}

/// The approved left-facing flame's animated moods, all bundled APNGs
/// (scripts/make-flame-assets.py): walking, working at the laptop
/// (a browser session is active), and the notification wiggle.
enum FlameAnimation: String {
    case walk = "FlameWalk"
    case laptop = "FlameLaptop"
    case notify = "FlameNotify"

    private static var cache: [FlameAnimation: [UIImage]] = [:]

    var frames: [UIImage] {
        if let cached = Self.cache[self] { return cached }
        guard let url = Bundle.main.url(forResource: rawValue, withExtension: "png"),
              let source = CGImageSourceCreateWithURL(url as CFURL, nil) else { return [] }
        let count = CGImageSourceGetCount(source)
        let decoded = (0..<count).compactMap { index in
            CGImageSourceCreateImageAtIndex(source, index, nil).map { UIImage(cgImage: $0) }
        }
        Self.cache[self] = decoded
        return decoded
    }
}

/// Reduce Motion and a backgrounded app both rest on the static mark.
struct AnimatedFlame: View {
    var animation: FlameAnimation = .walk
    var size: CGFloat = 62
    @Environment(\.accessibilityReduceMotion) private var reduceMotion
    @Environment(\.scenePhase) private var scenePhase

    var body: some View {
        let frames = animation.frames
        Group {
            if reduceMotion || frames.isEmpty {
                FlameMark(size: size)
            } else {
                TimelineView(.animation(minimumInterval: 0.04, paused: scenePhase != .active)) { context in
                    let index = Int(context.date.timeIntervalSinceReferenceDate / 0.04) % frames.count
                    Image(uiImage: frames[index])
                        .resizable()
                        .scaledToFit()
                        .frame(width: size, height: size * 1.25)
                        .accessibilityHidden(true)
                }
                .frame(width: size, height: size * 1.25)
            }
        }
    }
}

enum FlameState { case asleep, working, needsYou(Int), celebrating, thinking }

struct FloatingFlame: View {
    var state: FlameState
    var dimmed: Bool = false
    var traveling = false
    var browsing = false
    var onTap: () -> Void
    var onLongPress: (() -> Void)? = nil
    var onDragBegan: (() -> Void)? = nil
    var onDragEnded: ((CGSize?) -> Void)? = nil
    @Environment(FlamePlayStore.self) private var playStore

    /// Tunable in Flame Lab. Default 122: about half again the 81pt flame
    /// of the first interactive build.
    private var size: CGFloat { CGFloat(playStore.settings.homeFlameSize) }
    private var frameHeight: CGFloat { size * 1.25 + 18 }
    /// The artwork carries ~16–18% transparent canvas under his feet, so
    /// anchoring to the image edge left him floating far above the bottom.
    /// Drop him by that slack so his *feet* sit near the feed's edge.
    private var feetDrop: CGFloat { size * 1.25 * 0.165 + 6 }

    private var needsYou: Bool { if case .needsYou = state { return true }; return false }

    var body: some View {
        // The flame is a character, not a button in a disc (mocks):
        // big, sticker-like, soft shadow only — a layered rig with
        // moving limbs and faces; a live browser session brings out
        // the rig's own laptop and he types on it.
        FlameActor(size: size,
                   attention: needsYou,
                   browsing: browsing,
                   movable: onDragEnded != nil,
                   traveling: traveling,
                   onTap: onTap,
                   onLongPress: onLongPress,
                   onDragBegan: onDragBegan,
                   onDragEnded: onDragEnded)
            .overlay(alignment: .topLeading) {
                if case .needsYou(let count) = state, count > 0 {
                    Text("\(count)")
                        .font(.system(size: 11, weight: .bold)).foregroundStyle(.white)
                        .padding(.horizontal, 6).padding(.vertical, 2)
                        .background(HyggeTheme.emberDeep, in: Capsule())
                        // The artwork includes transparent padding; anchor
                        // to the character's shoulder, not the image corner.
                        .offset(x: 18 * size / 108, y: 28 * size / 108)
                        .allowsHitTesting(false)
                }
            }
            .frame(width: size + 14, height: frameHeight, alignment: .bottom)
            .offset(y: feetDrop)
            .opacity(dimmed ? 0.35 : 1)
            .animation(.easeInOut(duration: 0.25), value: dimmed)
            .accessibilityLabel(accessibilityText)
            .accessibilityAddTraits(.isButton)
            .accessibilityAction { onTap() }
    }

    private var accessibilityText: String {
        switch state {
        case .asleep: return "Talk to Hygge"
        case .needsYou(let n): return "Talk to Hygge, \(n) thing\(n == 1 ? "" : "s") need you"
        case .celebrating: return "Talk to Hygge, something good just landed"
        case .thinking: return "Talk to Hygge, Hygge is working"
        case .working: return "Talk to Hygge, Hygge is browsing for you right now"
        }
    }

}
